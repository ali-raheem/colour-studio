#!/usr/bin/env python3
"""Stamp a build version into the app before deploying.

    python3 scripts/build_version.py

Writes `js/version.js` (read by the footer's "Build …" line) and rewrites `sw.js`'s
`VERSION` constant to match, so the two can never drift out of sync and a deploy can
never go out with a stale cache name. Run this once, right before every deploy —
`README.md` and `sw.js`'s own comment both point back here instead of describing a
manual step, because a step nobody has to remember is a step nobody forgets.

The version is the repo's short commit hash when this is a git checkout (so it reads
like a real build id); otherwise it falls back to a short hash of the tracked files'
contents, which still changes exactly when the deployed bytes change.

Workflow in a git checkout: commit your real changes FIRST, then run this script, then
deploy. It stamps whatever HEAD already is — it can't embed its own commit's hash,
since running it and then committing the result would just move HEAD again (a file
can't contain the hash of the commit that adds it). So `sw.js`'s stamped VERSION line
is always exactly one commit "behind" if you commit it on its own; that's expected,
not a bug, and not worth chasing — don't loop running this script and committing the
result. Either leave the stamp uncommitted between deploys (`js/version.js` already
is, permanently — see .gitignore), or fold `sw.js`'s one-line change into your next
real commit instead of giving it a commit of its own.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

# Everything that affects what ships. Keep this in sync with sw.js's own ASSETS list
# (tests/sw.test.js checks that list against index.html, but not against this one).
TRACKED = [
    "index.html", "style.css",
    "js/color.js", "js/names.js", "js/palettes.js", "js/app.js",
    "manifest.webmanifest",
    "icons/icon.svg", "icons/icon-192.png", "icons/icon-512.png",
    "icons/icon-maskable-512.png", "icons/apple-touch-icon.png",
]


def content_hash():
    h = hashlib.sha256()
    for rel in sorted(TRACKED):
        with open(os.path.join(ROOT, rel), "rb") as f:
            h.update(rel.encode())
            h.update(f.read())
    return h.hexdigest()[:10]


def git_commit():
    try:
        out = subprocess.run(
            ["git", "-C", ROOT, "rev-parse", "--short=10", "HEAD"],
            capture_output=True, text=True, timeout=5,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() if out.returncode == 0 else None


def write_version_js(version, built):
    path = os.path.join(ROOT, "js", "version.js")
    payload = json.dumps({"version": version, "built": built})
    content = (
        "// AUTO-GENERATED by scripts/build_version.py — do not edit by hand.\n"
        f"window.APP_VERSION = {payload};\n"
    )
    with open(path, "w") as f:
        f.write(content)
    print(f"wrote js/version.js: {version} @ {built}")


def stamp_service_worker(version):
    path = os.path.join(ROOT, "sw.js")
    sw = open(path).read()
    new_sw, n = re.subn(r"const VERSION = '[^']*';", f"const VERSION = 'v{version}';", sw, count=1)
    if n != 1:
        sys.exit("sw.js: could not find `const VERSION = '...';` to stamp")
    if new_sw == sw:
        print("sw.js: VERSION already up to date")
        return
    open(path, "w").write(new_sw)
    print(f"stamped sw.js: VERSION = 'v{version}'")


def main():
    version = git_commit() or content_hash()
    built = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    write_version_js(version, built)
    stamp_service_worker(version)


if __name__ == "__main__":
    main()
